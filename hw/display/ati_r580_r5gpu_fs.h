/* the pixel: program, alpha test, channel selects, blend, mask, pack */
static const char r5g_fs_main[] =
"uint om_pixel()\n"
"{\n"
"    us_out[0] = vec4(0.0); us_out[1] = vec4(0.0);\n"
"    us_out[2] = vec4(0.0); us_out[3] = vec4(0.0);\n"
"    us_killed = false; us_depth_written = false; us_depth = 0.0;\n"
"    us_keep = false;\n"
"    us_run();\n"
"    if (us_killed) return 0u;\n"
"    vec4 col = us_out[0];\n"
"    ivec4 k0 = ivec4(0, S_CF, S_CMASK, S_FL), cs = S_CS, b0 = S_B0, b1 = S_B1;\n"
"    if ((k0.w & 2) != 0 && !om_atest(b1.w, col.w, R5_KF(1).x)) return 0u;\n"
"    vec4 src = vec4(col[cs.x], col[cs.y], col[cs.z], col[cs.w]);\n"
"    if ((k0.w & 8) != 0 && om_discard(b1.z, src)) return 0u;\n"
"    vec4 d = vec4(0.0, 0.0, 0.0, 1.0);\n"
"    if ((k0.w & 4) != 0) d = om_unpack(k0.y, R5_DST);\n"
"    vec4 res = src;\n"
"    if ((k0.w & 1) != 0) {\n"
"        vec4 k = R5_KF(0);\n"
"        res.x = om_blend(b0.x, b0.y, b0.z, 0, src, d, k);\n"
"        res.y = om_blend(b0.x, b0.y, b0.z, 1, src, d, k);\n"
"        res.z = om_blend(b0.x, b0.y, b0.z, 2, src, d, k);\n"
"        res.w = om_blend(b0.w, b1.x, b1.y, 3, src, d, k);\n"
"    }\n"
"    if ((k0.z & 1) == 0) res.x = d.x;\n"
"    if ((k0.z & 2) == 0) res.y = d.y;\n"
"    if ((k0.z & 4) == 0) res.z = d.z;\n"
"    if ((k0.z & 8) == 0) res.w = d.w;\n"
"    ivec2 px = ivec2(R5_FRAG) - R5_KI(9).xy;\n"
"    int code = 0;\n"
"    for (int i = 0; i < 4; i++) {\n"
"        ivec4 r = R5_KI(5 + i);\n"
"        if (px.x >= r.x && px.x <= r.z && px.y >= r.y && px.y <= r.w) code |= 1 << i;\n"
"    }\n"
"    if (((R5_KI(4).x >> code) & 1) == 0) return 0u;\n"
"    us_keep = true;\n"
"    return om_pack(k0.y, res);\n"
"}\n";

